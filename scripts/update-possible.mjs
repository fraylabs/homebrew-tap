import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const api = "https://api.github.com/repos/fraylabs/possible/releases/latest";
const fixture = process.argv[2] === "--fixture" ? process.argv[3] : undefined;
async function download(url) {
  const response = await fetch(url, { headers: { Accept: "application/vnd.github+json" } });
  if (!response.ok) throw new Error(`Download failed (${response.status}): ${url}`);
  return response.text();
}
const release = JSON.parse(fixture ? await readFile(join(fixture, "release.json"), "utf8") : await download(api));
if (!/^v[0-9]+\.[0-9]+\.[0-9]+$/.test(release.tag_name) || release.draft || release.prerelease) throw new Error("Latest release must be a published stable version");
const version = release.tag_name.slice(1);
const assets = release.assets ?? [];
if (!assets.some(asset => asset.name === "SHA256SUMS")) {
  console.log(`${release.tag_name} has no standalone checksums yet; nothing to update`);
  process.exit(0);
}
const base = `https://github.com/fraylabs/possible/releases/download/${release.tag_name}`;
const sums = fixture ? await readFile(join(fixture, "SHA256SUMS"), "utf8") : await download(`${base}/SHA256SUMS`);
const target = "Formula/possible.rb";
const previous = await readFile(target, "utf8").catch(error => { if (error.code === "ENOENT") return ""; throw error; });
const oldVersion = previous.match(/version "([0-9.]+)"/)?.[1];
if (oldVersion && oldVersion.localeCompare(version, undefined, { numeric: true }) > 0) {
  console.log(`Tap ${oldVersion} is newer than ${version}; nothing to update`);
  process.exit(0);
}
const entry = (os, arch) => {
  const archive = `possible-v${version}-${os}-${arch}.tar.gz`;
  if (assets.filter(asset => asset.name === archive).length !== 1) throw new Error(`Missing or ambiguous release asset ${archive}`);
  const matches = sums.trim().split("\n").map(line => line.trim().split(/\s+/)).filter(([, name]) => name === archive);
  if (matches.length !== 1 || !/^[0-9a-f]{64}$/.test(matches[0][0])) throw new Error(`Missing or ambiguous checksum for ${archive}`);
  return `      url "${base}/${archive}"\n      sha256 "${matches[0][0]}"`;
};
const formula = `# Generated by this tap's update-possible workflow from published SHA256SUMS.
class Possible < Formula
  desc "Discover, author, and capture source-owned AI Outcomes"
  homepage "https://possible.sh"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${entry("darwin", "arm64")}
    end
    on_intel do
${entry("darwin", "x64")}
    end
  end

  on_linux do
    on_arm do
${entry("linux", "arm64")}
    end
    on_intel do
${entry("linux", "x64")}
    end
  end

  def install
    bin.install "possible"
    pkgshare.install "LICENSE", "NODE-LICENSE"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/possible --version").strip
    system bin/"possible", "create", "smoke", "--product", "example/product"
    assert_match "Validated 1 Outcome", shell_output("#{bin}/possible validate")
  end
end
`;
if (oldVersion === version && previous !== formula) throw new Error("Published checksums changed for the installed version; inspect before updating");
await mkdir("Formula", { recursive: true });
await writeFile(target, formula);
console.log(previous === formula ? `Possible ${version} is current` : `Updated Possible to ${version} using published SHA256SUMS`);
